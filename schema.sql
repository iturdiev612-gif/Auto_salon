-- TURDIEV AUTO 2.0 — run in Supabase SQL Editor.
-- Creates cars, profiles and bookings tables with row-level security.
-- Do not expose service_role/secret keys in frontend.

create extension if not exists pgcrypto;

create table if not exists public.cars (
  id bigint generated by default as identity primary key,
  brand text not null check (brand in ('Mercedes-Benz','Toyota','BMW')),
  model text not null,
  year integer not null check (year between 1990 and 2035),
  price numeric(12,2) not null check (price > 0),
  body text not null,
  engine text not null,
  fuel_liters numeric default 0,
  horsepower integer default 0,
  drive text,
  mileage_km integer default 0,
  image_url text,
  description text,
  history text,
  created_at timestamptz not null default now()
);

create table if not exists public.profiles (
  id uuid primary key references auth.users(id) on delete cascade,
  display_name text,
  role text not null default 'user' check (role in ('user','admin')),
  created_at timestamptz not null default now()
);

create table if not exists public.bookings (
  id uuid primary key default gen_random_uuid(),
  user_id uuid references auth.users(id) on delete set null,
  customer_name text not null,
  phone text not null,
  car_id bigint references public.cars(id) on delete set null,
  booking_type text not null check (booking_type in ('Встреча в автосалоне','Онлайн-консультация')),
  comment text,
  status text not null default 'new' check (status in ('new','contacted','confirmed','cancelled')),
  created_at timestamptz not null default now()
);

create index if not exists cars_brand_idx on public.cars(brand);
create index if not exists cars_price_idx on public.cars(price);
create index if not exists bookings_user_idx on public.bookings(user_id);

-- Automatically create a regular profile for every newly registered Auth user.
create or replace function public.handle_new_user_profile()
returns trigger language plpgsql security definer set search_path = public
as $$
begin
  insert into public.profiles (id, display_name, role)
  values (new.id, coalesce(new.raw_user_meta_data->>'display_name', split_part(new.email, '@', 1)), 'user')
  on conflict (id) do nothing;
  return new;
end;
$$;

drop trigger if exists on_auth_user_created_profile on auth.users;
create trigger on_auth_user_created_profile
after insert on auth.users
for each row execute procedure public.handle_new_user_profile();

alter table public.cars enable row level security;
alter table public.profiles enable row level security;
alter table public.bookings enable row level security;

-- Helper checks role using profiles. Only owner manually promotes a user to admin.
create or replace function public.is_admin()
returns boolean language sql stable security definer
set search_path = public
as $$ select exists(select 1 from public.profiles p where p.id = auth.uid() and p.role = 'admin'); $$;

drop policy if exists "Public can read cars" on public.cars;
create policy "Public can read cars" on public.cars for select to anon, authenticated using (true);
drop policy if exists "Admins insert cars" on public.cars;
create policy "Admins insert cars" on public.cars for insert to authenticated with check (public.is_admin());
drop policy if exists "Admins update cars" on public.cars;
create policy "Admins update cars" on public.cars for update to authenticated using (public.is_admin()) with check (public.is_admin());
drop policy if exists "Admins delete cars" on public.cars;
create policy "Admins delete cars" on public.cars for delete to authenticated using (public.is_admin());

drop policy if exists "Users read own profile" on public.profiles;
create policy "Users read own profile" on public.profiles for select to authenticated using (id = auth.uid() or public.is_admin());
drop policy if exists "Users create own profile" on public.profiles;
create policy "Users create own profile" on public.profiles for insert to authenticated with check (id = auth.uid() and role = 'user');
drop policy if exists "Users update own display name" on public.profiles;
create policy "Users update own display name" on public.profiles for update to authenticated using (id = auth.uid() and role = 'user') with check (id = auth.uid() and role = 'user');

drop policy if exists "Users create booking" on public.bookings;
create policy "Users create booking" on public.bookings for insert to anon, authenticated with check (user_id is null or user_id = auth.uid());
drop policy if exists "Users read own bookings" on public.bookings;
create policy "Users read own bookings" on public.bookings for select to authenticated using (user_id = auth.uid() or public.is_admin());
drop policy if exists "Admins update bookings" on public.bookings;
create policy "Admins update bookings" on public.bookings for update to authenticated using (public.is_admin()) with check (public.is_admin());
drop policy if exists "Admins delete bookings" on public.bookings;
create policy "Admins delete bookings" on public.bookings for delete to authenticated using (public.is_admin());

